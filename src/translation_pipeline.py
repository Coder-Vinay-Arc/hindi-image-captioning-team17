"""
translation_pipeline.py -- Approach 3: English captioning + Hindi translation.

Pipeline: image -> BLIP English caption -> Hindi translation -> results CSV.
The CSV has columns file_name, prediction and is scored by evaluate.py:

    python src/translation_pipeline.py --split test
    python src/evaluate.py --model translation --split test --pred_csv results/translation_test_preds.csv

Options:
    --limit 20          quick smoke test (uses a separate output file by default)
    --gold_english      translate the dataset's gold English captions instead of BLIP (MT upper bound)
    --translator marian local Helsinki-NLP/opus-mt-en-hi, batched and offline (default)
    --translator google Google Translate through deep-translator (needs internet)
    --out PATH          output CSV (default results/translation_<split>_preds.csv)
    --num_beams 4       MT beam width (default 4; 1 = greedy)
    --no_repeat_ngram_size 2  block repeated n-grams in the Hindi output (default 2)

Rerunning the same command resumes: rows already present in the output CSV are skipped.
Resume keeps the old rows, so after changing decoding options use a new --out path
(e.g. results/translation_test_beam_preds.csv) to regenerate all predictions.
The Google backend fails with a clear error if the service is blocked or rate-limited;
the default local MarianMT backend needs no internet.
"""

# argparse reads command-line options such as --split, --limit and --translator.
import argparse
# os builds file paths and creates the output directory.
import os
# sys lets us force UTF-8 printing so Hindi text is shown correctly on Windows.
import sys
# time is used to pause between Google Translate requests and to back off on errors.
import time

# pandas reads captions.csv and writes the prediction CSV.
import pandas as pd
# PIL.Image opens each region crop and converts it to RGB.
from PIL import Image
# tqdm displays progress bars for the captioning and translation loops.
from tqdm import tqdm


# Define all command-line arguments accepted by this script.
def parse_args():
    # Create the parser with a description shown by --help.
    ap = argparse.ArgumentParser(description="English captioning (BLIP) + Hindi translation pipeline")
    # Which processed split to run on: train, dev or test.
    ap.add_argument("--split", default="test")
    # Root folder that contains the split folders (each has captions.csv and images/).
    ap.add_argument("--data_root", default="data/processed")
    # Optional custom output CSV path; the default is built later from the split name.
    ap.add_argument("--out", default=None)
    # If N > 0, only the first N rows are processed (useful for a quick smoke test).
    ap.add_argument("--limit", type=int, default=0, help="only first N rows (smoke test)")
    # Hugging Face model that turns each image into an English caption.
    ap.add_argument("--caption_model", default="Salesforce/blip-image-captioning-base")
    # Hugging Face model that translates English text into Hindi.
    ap.add_argument("--mt_model", default="Helsinki-NLP/opus-mt-en-hi")
    # Translation backend: local MarianMT (default, offline) or online Google Translate.
    ap.add_argument("--translator", choices=["marian", "google"], default="marian")
    # Maximum number of new tokens generated by BLIP and MarianMT.
    ap.add_argument("--max_new_tokens", type=int, default=30)
    # Number of images/captions processed together in one forward pass.
    ap.add_argument("--batch_size", type=int, default=8)
    # Beam width for MT decoding; 4 gives better Hindi than greedy (1) at little extra cost.
    ap.add_argument("--num_beams", type=int, default=4)
    # Block repeated n-grams so the MT model cannot loop ("फूल फूल फूल ...").
    ap.add_argument("--no_repeat_ngram_size", type=int, default=2)
    # Length penalty for beam search; 1.0 is neutral (no bias towards shorter/longer output).
    ap.add_argument("--length_penalty", type=float, default=1.0)
    # If set, skip BLIP and translate the dataset's gold English captions (MT upper bound).
    ap.add_argument("--gold_english", action="store_true", help="translate gold English captions instead of BLIP")
    # Delay in seconds between Google requests to avoid rate limiting.
    ap.add_argument("--sleep", type=float, default=0.2, help="delay between Google translation requests")
    # Parse the command line and return the populated namespace.
    return ap.parse_args()


# Write the predictions finished so far to disk, so a crash does not lose work.
def save_partial(done, out_path):
    # Build a two-column table (file_name, prediction) from the ordered results dictionary.
    pd.DataFrame({"file_name": list(done), "prediction": list(done.values())}).to_csv(
        # No pandas index column; UTF-8 keeps Devanagari characters intact.
        out_path, index=False, encoding="utf-8")


# Translate one English string with Google Translate, retrying on network errors.
def translate_google(text, translator, retries=5):
    # An empty English caption needs no network request.
    if not str(text).strip():
        # Return an empty prediction immediately.
        return ""
    # Try at most `retries` times before giving up.
    for attempt in range(retries):
        # Catch any network/API error so one bad request does not stop the whole run.
        try:
            # Send the English text to Google and receive the Hindi translation.
            out = translator.translate(text)
            # Accept only a non-empty response and remove surrounding whitespace.
            if out:
                # Return the cleaned Hindi translation.
                return out.strip()
        # On failure, wait longer after each attempt (linear backoff).
        except Exception:
            # Sleep 1.5s, then 3s, then 4.5s, ... before retrying.
            time.sleep(1.5 * (attempt + 1))
    # Warn because this row will be empty and will lower the score.
    print(f"warning: Google translation failed for {str(text)[:60]!r}")
    # All attempts failed: return an empty prediction, counted later as `empty`.
    return ""


# Entry point: generate English captions (or use gold English) and translate them to Hindi.
def main():
    # Read all command-line options.
    args = parse_args()
    # Import torch here so --help works without loading the heavy dependency first.
    import torch

    # Folder of the selected split, e.g. data/processed/test.
    split_dir = os.path.join(args.data_root, args.split)
    # Read the split's caption table; keep empty strings instead of NaN values.
    df = pd.read_csv(os.path.join(split_dir, "captions.csv"), keep_default_na=False)
    # If --limit was given, keep only the first N rows for a smoke test.
    if args.limit:
        # .copy() avoids a pandas warning when slicing later.
        df = df.head(args.limit).copy()
    # Use --out if given, otherwise build a default path.
    if args.out:
        # Explicit output path from the user.
        out_path = args.out
    elif args.limit:
        # Smoke tests must not overwrite the full results file.
        out_path = os.path.join("results", f"translation_{args.split}_limit{args.limit}_preds.csv")
    else:
        # Normal full-run output path.
        out_path = os.path.join("results", f"translation_{args.split}_preds.csv")
    # Create the output folder if needed; "." covers a bare file name.
    os.makedirs(os.path.dirname(out_path) or ".", exist_ok=True)

    # Dictionary mapping file_name -> Hindi prediction, used for resume and final output.
    done = {}
    # If an output CSV already exists, load it so finished rows can be skipped.
    if os.path.exists(out_path):
        # Read previous predictions and keep empty strings as empty strings.
        old = pd.read_csv(out_path, encoding="utf-8", keep_default_na=False)
        # Keep only non-empty predictions, keyed by file name (empty ones will be redone).
        done = {str(f): str(p) for f, p in zip(old["file_name"], old["prediction"]) if str(p).strip()}
        # Report how many rows are already complete.
        print(f"resuming: {len(done)} rows already done")
        # Warn that a settings change will not update the already saved rows.
        print("note: existing rows are kept; use a new --out path to regenerate them")

    # Ordered list of every image file name in this split.
    names = df["file_name"].astype(str).tolist()
    # Indices of rows that still need a caption/translation.
    pending = [i for i, n in enumerate(names) if n not in done]
    # If everything is already done, stop without loading any model.
    if not pending:
        # Tell the user the output file is complete.
        print(f"nothing to do: {out_path} is complete")
        # Exit main() early.
        return

    # Use the GPU when available, otherwise fall back to the CPU.
    device = "cuda" if torch.cuda.is_available() else "cpu"

    # Branch A: use the dataset's gold English captions (translation upper bound).
    if args.gold_english:
        # Copy the gold English caption for every pending row.
        english = {i: str(df.iloc[i]["english_caption"]) for i in pending}
    # Branch B: generate English captions from the images with BLIP.
    else:
        # Import BLIP only when image captioning is actually needed.
        from transformers import BlipForConditionalGeneration, BlipProcessor

        # Report which captioning model and device are being used.
        print(f"loading {args.caption_model} on {device}")
        # Load the BLIP processor (resizes and normalises pixels for the model).
        processor = BlipProcessor.from_pretrained(args.caption_model)
        # Load the BLIP model, move it to the device, and switch to inference mode.
        model = BlipForConditionalGeneration.from_pretrained(args.caption_model).to(device).eval()
        # Dictionary mapping pending row index -> generated English caption.
        english = {}
        # Process pending images in batches, showing a progress bar.
        for start in tqdm(range(0, len(pending), args.batch_size), desc="BLIP English captions"):
            # Indices of the rows in the current batch.
            idxs = pending[start:start + args.batch_size]
            # Collected RGB images for the current batch.
            images = []
            # Load every image of this batch from <split_dir>/images/<file_name>.
            for i in idxs:
                # Build the path of image i.
                path = os.path.join(split_dir, "images", names[i])
                # Open the region crop and convert it to RGB (BLIP needs 3 channels).
                images.append(Image.open(path).convert("RGB"))
            # Preprocess the batch and move the tensors to the selected device.
            inputs = processor(images=images, return_tensors="pt").to(device)
            # Disable gradient tracking because we only run inference.
            with torch.no_grad():
                # Generate one English caption per image.
                ids = model.generate(**inputs, max_new_tokens=args.max_new_tokens)
            # Decode the token IDs into text and store each caption by row index.
            for i, cap in zip(idxs, processor.batch_decode(ids, skip_special_tokens=True)):
                # Save the stripped English caption for this row.
                english[i] = cap.strip()

    # Translation branch 1: local MarianMT/Opus-MT model (default, runs offline).
    if args.translator == "marian":
        # Import the MarianMT model and tokenizer only for this backend.
        from transformers import MarianMTModel, MarianTokenizer

        # Report which translation model and device are being used.
        print(f"loading {args.mt_model} on {device}")
        # Load the English-to-Hindi tokenizer.
        tokenizer = MarianTokenizer.from_pretrained(args.mt_model)
        # Load the English-to-Hindi model, move it to the device, and set inference mode.
        mt_model = MarianMTModel.from_pretrained(args.mt_model).to(device).eval()
        # Translate pending English captions in batches with a progress bar.
        for start in tqdm(range(0, len(pending), args.batch_size), desc="EN -> HI translation"):
            # Indices of the rows in the current translation batch.
            idxs = pending[start:start + args.batch_size]
            # English texts for this batch; an empty string guards missing captions.
            texts = [english.get(i, "") or "" for i in idxs]
            # Tokenise and pad the batch, truncating very long inputs to 64 tokens.
            inputs = tokenizer(texts, return_tensors="pt", padding=True, truncation=True, max_length=64).to(device)
            # Disable gradient tracking because we only run inference.
            with torch.no_grad():
                # Generate Hindi token IDs with beam search and repetition blocking.
                ids = mt_model.generate(
                    **inputs,
                    max_new_tokens=args.max_new_tokens,
                    num_beams=args.num_beams,
                    no_repeat_ngram_size=args.no_repeat_ngram_size,
                    length_penalty=args.length_penalty,
                    early_stopping=args.num_beams > 1,
                )
            # Decode Hindi token IDs and store the result for each row.
            for k, (i, hindi) in enumerate(zip(idxs, tokenizer.batch_decode(ids, skip_special_tokens=True))):
                # Keep an empty English caption empty instead of translating an empty string.
                done[names[i]] = hindi.strip() if texts[k].strip() else ""
            # Save after every batch so a crash keeps all finished predictions.
            save_partial(done, out_path)
    # Translation branch 2: online Google Translate (slower, one request at a time).
    else:
        # Import the free Google Translate wrapper.
        from deep_translator import GoogleTranslator

        # Create an English-to-Hindi translator.
        translator = GoogleTranslator(source="en", target="hi")
        # Probe the service once so a blocked/quota-limited run stops immediately.
        if not translate_google("hello", translator):
            # Tell the user how to switch to the offline backend.
            print("error: Google Translate is unavailable (blocked or rate-limited); use --translator marian")
            # Stop before wasting hours on a run that would only save empty rows.
            return
        # Translate one pending caption at a time with a progress bar.
        for i in tqdm(pending, desc="EN -> HI translation"):
            # Translate the English caption and store the Hindi result.
            done[names[i]] = translate_google(english.get(i, ""), translator)
            # Pause briefly to reduce the chance of being rate-limited.
            time.sleep(args.sleep)
            # Save every 20 rows as a checkpoint.
            if len(done) % 20 == 0:
                # Write the current predictions to disk.
                save_partial(done, out_path)

    # Build the final table in the original CSV order, using "" for any missing row.
    result = pd.DataFrame({"file_name": names, "prediction": [done.get(n, "") for n in names]})
    # Write the complete predictions to the requested output path.
    result.to_csv(out_path, index=False, encoding="utf-8")
    # Count empty predictions so failed translations are easy to spot.
    empty = int((result["prediction"].str.strip() == "").sum())
    # Print a short completion summary: row count, output path and empty count.
    print(f"saved {len(result)} rows -> {out_path} (empty: {empty})")


# Run the pipeline only when this file is executed directly, not when imported.
if __name__ == "__main__":
    # Force UTF-8 on Windows so Hindi text prints without encoding errors.
    sys.stdout.reconfigure(encoding="utf-8")
    # Start the pipeline.
    main()
